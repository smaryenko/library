// Preview scene for Race Day — consumed by tools/build-previews.js (node only;
// not loaded by the book page). Turbo and Bolt, built with the book's own
// car.js, neck and neck on the living-room floor by the orange loop.

module.exports = (h) => {
  const { buildCar } = h.load('race', 'assets/js/car.js');

  function scene(W, H, k, title, L) {
    const floorY = H * 0.5;
    const sq = 14 * k, bandY = H * 0.86;
    let checker = '';
    for (let i = 0; i * sq < W; i++) for (let r = 0; r < 2; r++) {
      if ((i + r) % 2 === 0) checker += `<rect x="${(i * sq).toFixed(1)}" y="${(bandY + r * sq).toFixed(1)}" width="${sq.toFixed(1)}" height="${sq.toFixed(1)}" fill="#fff"/>`;
    }
    let boards = '';
    for (let i = 1; i < 7; i++) {
      const y = floorY + (H - floorY) * Math.pow(i / 7, 1.4);
      boards += `<line x1="0" y1="${y.toFixed(1)}" x2="${W}" y2="${y.toFixed(1)}" stroke="#b8925e" stroke-width="${(1.5 * k).toFixed(1)}" opacity="0.5"/>`;
    }
    const by = H * 0.12, N = 12;
    let flags = '';
    for (let i = 1; i < N; i++) {
      const t = i / N, x = W * t, y = by + Math.sin(Math.PI * t) * 26 * k;
      flags += `<path d="M${(x - 9 * k).toFixed(1)} ${y.toFixed(1)} L${(x + 9 * k).toFixed(1)} ${y.toFixed(1)} L${x.toFixed(1)} ${(y + 17 * k).toFixed(1)} Z" fill="${i % 2 ? '#e23b2e' : '#ffffff'}"/>`;
    }
    const turbo = buildCar({ body: '#E23B2E', cabin: '#b2271c', number: '1', spoiler: 'wing', stripe: 'center' });
    const bolt = buildCar({ body: '#2F7DE0', cabin: '#235fab', number: '7', spoiler: 'tall', stripe: 'center' });
    const lc = L.loop;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for Race Day — generated by tools/build-previews.js from
       books/race/preview.js. Original vector. -->
  <defs>
    <linearGradient id="pxWall" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#f6ecd8"/><stop offset="100%" stop-color="#e8d6b6"/>
    </linearGradient>
    <linearGradient id="pxFloor" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#d9b47e"/><stop offset="100%" stop-color="#c49a62"/>
    </linearGradient>
  </defs>
  <rect width="${W}" height="${floorY}" fill="url(#pxWall)"/>
  <rect y="${floorY - 10 * k}" width="${W}" height="${10 * k}" fill="#fffaf0"/>
  <rect y="${floorY}" width="${W}" height="${H - floorY}" fill="url(#pxFloor)"/>
  ${boards}
  <circle cx="${lc[0]}" cy="${lc[1]}" r="${lc[2]}" fill="none" stroke="#f4621f" stroke-width="${18 * k}"/>
  <circle cx="${lc[0]}" cy="${lc[1]}" r="${lc[2]}" fill="none" stroke="#ff8a4a" stroke-width="${6 * k}" opacity="0.7"/>
  <circle cx="${lc[0]}" cy="${lc[1]}" r="${lc[2] - 13 * k}" fill="none" stroke="#c84a12" stroke-width="${3 * k}"/>
  <path d="M0 ${by} Q${W / 2} ${by + 52 * k} ${W} ${by}" fill="none" stroke="#9aa0a8" stroke-width="${2 * k}"/>
  ${flags}
  <rect y="${bandY}" width="${W}" height="${2 * sq}" fill="#1b1e24"/>
  ${checker}
  ${h.embed(bolt, L.bolt[0], L.bolt[1], L.bolt[2])}
  ${h.embed(turbo, L.turbo[0], L.turbo[1], L.turbo[2])}
  ${title || ''}
</svg>
`;
  }

  return {
    cover: () => scene(h.COVER.W, h.COVER.H, 1, '', {
      loop: [300, 120, 74], bolt: [150, 90, 250], turbo: [-20, 120, 270] }),
    og: () => scene(h.OG.W, h.OG.H, 2.1,
      h.title(['Race', 'Day!'], ['#ffd54a', '#ff8a4a'], '#3a1a0c', 60, 150), {
        loop: [1020, 250, 160], bolt: [620, 180, 520], turbo: [340, 250, 560] })
  };
};
