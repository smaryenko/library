// Preview scene for the Christmas Storybook — consumed by
// tools/build-previews.js (node only; not loaded by the book page). The
// book's own tree, Rudolph and Santa's sleigh on a snowy night.

module.exports = (h) => {
  const { buildTree } = h.load('xmas', 'assets/js/tree.js');
  const { buildReindeer } = h.load('xmas', 'assets/js/reindeer.js');
  const { buildSanta } = h.load('xmas', 'assets/js/santa.js');

  function scene(W, H, k, title, L) {
    const rnd = h.rand(7);
    let snow = '', stars = '';
    for (let i = 0; i < 70; i++) {
      snow += `<circle cx="${(rnd() * W).toFixed(0)}" cy="${(rnd() * H * 0.85).toFixed(0)}" r="${((1 + rnd() * 2.4) * k).toFixed(1)}" fill="#fff" opacity="${(0.5 + rnd() * 0.5).toFixed(2)}"/>`;
    }
    for (let i = 0; i < 26; i++) {
      stars += `<circle cx="${(rnd() * W).toFixed(0)}" cy="${(rnd() * H * 0.5).toFixed(0)}" r="${(0.8 * k).toFixed(1)}" fill="#fff8d0" opacity="${(0.4 + rnd() * 0.6).toFixed(2)}"/>`;
    }
    const G = H * 0.8;
    const deer = buildReindeer({ fur: '#A9743B', furDark: '#8A5A28', belly: '#E9CBA0',
      antlerStyle: 'wide', antlerColor: '#7a4a2b', nose: 'red', accessory: 'scarf-red' });
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for the Christmas Storybook — generated by
       tools/build-previews.js from books/xmas/preview.js. Original vector. -->
  <defs>
    <linearGradient id="pxSky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#0a1b3a"/><stop offset="60%" stop-color="#1c3768"/>
      <stop offset="100%" stop-color="#34508a"/>
    </linearGradient>
    <radialGradient id="pxMoon" cx="50%" cy="50%" r="50%">
      <stop offset="0%" stop-color="#fff8d6"/><stop offset="70%" stop-color="#f3e6a8"/>
      <stop offset="100%" stop-color="rgba(243,230,168,0)"/>
    </radialGradient>
    <linearGradient id="pxSnow" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#f4f8ff"/><stop offset="100%" stop-color="#cfdcf0"/>
    </linearGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#pxSky)"/>
  ${stars}
  <circle cx="${L.moon[0]}" cy="${L.moon[1]}" r="${46 * k}" fill="url(#pxMoon)"/>
  <circle cx="${L.moon[0]}" cy="${L.moon[1]}" r="${26 * k}" fill="#fff6d0"/>
  ${h.embed(buildSanta(), L.santa[0], L.santa[1], L.santa[2])}
  <path d="M0 ${G} q${W * 0.25} ${-22 * k} ${W * 0.5} ${-4 * k} t${W * 0.5} ${-6 * k} L${W} ${H} L0 ${H} Z" fill="url(#pxSnow)"/>
  ${h.embed(buildTree(), L.tree[0], L.tree[1], L.tree[2])}
  ${h.embed(deer, L.deer[0], L.deer[1], L.deer[2])}
  ${snow}
  ${title || ''}
</svg>
`;
  }

  return {
    cover: () => scene(h.COVER.W, h.COVER.H, 1, '', {
      moon: [330, 60], santa: [150, 10, 120], tree: [-10, 70, 230], deer: [190, 90, 210] }),
    og: () => scene(h.OG.W, h.OG.H, 2.1,
      h.title(['Christmas', 'Storybook'], ['#ffe08a', '#ffd54a'], '#0a1b3a', 60, 140), {
        moon: [1110, 90], santa: [560, 0, 260], tree: [530, 150, 470], deer: [820, 210, 420] })
  };
};
