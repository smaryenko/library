// Preview scene for "A Day on the Reef" — consumed by tools/build-previews.js
// (node only; not loaded by the book page). The clownfish faces the runaway
// conch shell on a sunlit reef, drawn with the book's own reeflife.js helpers.

module.exports = (h) => {
  const R = h.load('reef', 'assets/js/reeflife.js');

  function scene(W, H, k, extra) {
    const SX = W * 0.74, SY = H * 0.7;
    const shell = R.drawConch({ x: SX, y: SY, s: 0.5 * k, uid: 'pv' });
    const FX = W * 0.32, FY = H * 0.53;
    const look = R.reefFaceToward(FX, FY, SX, SY - 10 * k, 22);
    const fish = R.drawClownfish({ x: FX, y: FY, s: 0.5 * k, flip: look.flip, tilt: look.tilt, pose: 'spot', uid: 'pv' });
    const sandY = SY + 30 * k;
    const bub = [[0.22, 0.30, 7], [0.25, 0.22, 5], [0.20, 0.15, 4], [0.86, 0.36, 6], [0.89, 0.27, 4]]
      .map(([x, y, r]) => `<circle cx="${(W * x).toFixed(0)}" cy="${(H * y).toFixed(0)}" r="${(r * k).toFixed(1)}" fill="rgba(234,255,255,0.18)" stroke="#eaffff" stroke-width="${(1.6 * k).toFixed(1)}"/>`).join('');
    const coral = (cx, base, s, col) => `<path transform="translate(${cx} ${base}) scale(${s})" d="M-60 0 q-6 -70 30 -74 q20 -30 34 0 q18 -40 32 2 q16 30 24 72 z" fill="${col}"/>
    <path transform="translate(${cx} ${base}) scale(${s})" d="M-30 -40 q20 -30 40 0 q-20 -14 -40 0 z" fill="#ffffff" opacity="0.25"/>`;
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for "A Day on the Reef" — generated by tools/build-previews.js
       from books/reef/preview.js. Original vector; nothing traced. -->
  <defs>
    <linearGradient id="pvWater" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#5fd3e0"/><stop offset="40%" stop-color="#1f9fc4"/>
      <stop offset="100%" stop-color="#075877"/>
    </linearGradient>
    <linearGradient id="pvSand" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#ecdcab"/><stop offset="100%" stop-color="#cdb87f"/>
    </linearGradient>
    ${shell.defs}${fish.defs}
  </defs>
  <rect width="${W}" height="${H}" fill="url(#pvWater)"/>
  <rect width="${W}" height="${H * 0.13}" fill="rgba(224,255,255,0.4)"/>
  <g fill="rgba(226,255,255,0.12)">
    <path d="M${W * 0.15} 0 l${W * 0.1} 0 l${W * 0.17} ${H * 0.87} l${-W * 0.14} 0 z"/>
    <path d="M${W * 0.45} 0 l${W * 0.13} 0 l${W * 0.2} ${H * 0.87} l${-W * 0.15} 0 z"/>
    <path d="M${W * 0.75} 0 l${W * 0.1} 0 l${W * 0.14} ${H * 0.87} l${-W * 0.11} 0 z"/>
  </g>
  <path d="M0 ${sandY - 8 * k} q${W * 0.3} ${-16 * k} ${W * 0.55} ${4 * k} t${W * 0.45} ${-4 * k} L${W} ${H} L0 ${H} Z" fill="url(#pvSand)"/>
  ${coral(W * 0.08, sandY + 6 * k, 0.9 * k, '#e2574e')}
  ${coral(W * 0.95, sandY + 4 * k, 0.75 * k, '#7b6fbf')}
  <path d="M${W * 0.9} ${sandY + 8 * k} q${-4 * k} ${-40 * k} ${-18 * k} ${-52 * k} M${W * 0.9} ${sandY + 8 * k} q${4 * k} ${-42 * k} ${18 * k} ${-56 * k}"
        fill="none" stroke="#5fbf8a" stroke-width="${9 * k}" stroke-linecap="round"/>
  <ellipse cx="${SX + 4 * k}" cy="${SY + 32 * k}" rx="${74 * k}" ry="${9 * k}" fill="rgba(4,40,58,0.24)"/>
  ${shell.shell}
  ${fish.back}${fish.body}${fish.front}
  ${bub}
  ${extra || ''}
</svg>
`;
  }

  return {
    cover: () => scene(h.COVER.W, h.COVER.H, 1),
    og: () => scene(h.OG.W, h.OG.H, 2.1,
      h.title(['A Day on', 'the Reef'], ['#ffe08a', '#ffd54a'], '#06384f', 60, 130))
  };
};
