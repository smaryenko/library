// Preview scene for "A Fox's Year" — consumed by tools/build-previews.js (node
// only; not loaded by the book page). Uses the book's own painted-fur fox and
// scene builders: the cover is the Autumn "Saving food" spread, the og image
// puts the Spring den spread next to the title.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
module.exports = (h) => {
  global.window = global;
  ['assets/js/furpaint.js', 'assets/js/nature.js', 'assets/js/fox.js', 'assets/js/scenes.js'].forEach(rel =>
    vm.runInThisContext(fs.readFileSync(path.join(h.BOOKS, 'seasons', rel), 'utf8')));
  // a scene SVG, data-parts + anim styles stripped, cropped to a box
  function fit(svg, x, y, w, hh, vb) {
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
      .replace(/<style>[\s\S]*?<\/style>/g, '').replace(/\sdata-part="[^"]*"/g, '');
    return `<svg x="${x}" y="${y}" width="${w}" height="${hh}" viewBox="${vb}" preserveAspectRatio="xMidYMid slice">${inner}</svg>`;
  }
  const head = (W, H) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for A Fox's Year — generated by tools/build-previews.js from
       books/seasons/preview.js. Original vector. -->`;
  return {
    // crop inside the plate so its rounded edge never shows
    cover: () => `${head(400, 300)}
  ${fit(buildCache(), 0, 0, 400, 300, '24 60 312 234')}
</svg>
`,
    og: () => `${head(1200, 630)}
  <defs><linearGradient id="ogBg" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="#f6e7c8"/><stop offset="1" stop-color="#e9b77c"/></linearGradient></defs>
  <rect width="1200" height="630" fill="url(#ogBg)"/>
  ${fit(buildSpringDen(), 560, 0, 640, 630, '70 60 238 234')}
  ${h.title(['A Fox\u2019s', 'Year'], ['#ffb46a', '#fff4e0'], '#4a3a22', 70, 270)}
</svg>
`
  };
};
