// Preview scene for "Where Does Rain Come From?": consumed by
// tools/build-previews.js (node only; not loaded by the book page). The
// cover and og image use the book's own crayon drawings (the rainbow and
// the puddle pages) on a kitchen table.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
module.exports = (h) => {
  global.window = global;
  ['../../assets/js/drawkit.js', 'assets/js/crayon.js', 'assets/js/scenes.js'].forEach(rel =>
    vm.runInThisContext(fs.readFileSync(path.join(h.BOOKS, 'rain', rel), 'utf8')));
  const S = window.RAIN_SCENES;
  // the drawings appear part by part in the book: in a static preview the
  // reveal animation is gone with the <style>, so nothing is hidden
  const table = (W, H) => `<defs>
    <linearGradient id="pvT" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#cfe6f4"/><stop offset="1" stop-color="#a9cfe6"/></linearGradient>
    <filter id="pvSh"><feGaussianBlur stdDeviation="${(W / 100).toFixed(1)}"/></filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#pvT)"/>`;
  const sheet = (svg, x, y, w) => `<rect x="${x + w * 0.02}" y="${y + w * 0.03}" width="${w}" height="${w}" fill="#2a4a6a" opacity="0.3" filter="url(#pvSh)"/>
  <rect x="${x}" y="${y}" width="${w}" height="${w}" fill="#fffdf6"/>${h.embed(svg, x, y, w)}`;
  const crayon = (x, y, a, c, s = 1) => `<g transform="translate(${x} ${y}) rotate(${a}) scale(${s})">
    <rect x="0" y="-11" width="150" height="22" rx="6" fill="${c}"/><rect x="22" y="-11" width="96" height="22" fill="#fff" opacity="0.35"/>
    <path d="M150 -11 Q176 -6 182 0 Q176 6 150 11 Z" fill="${c}"/></g>`;
  return {
    cover: () => {
      const { W, H } = h.COVER;
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for "Where Does Rain Come From?": generated by tools/build-previews.js
       from books/rain/preview.js using the book's own builders. Original. -->
  ${table(W, H)}
  ${sheet(S.rainbow(), 62, 12, 276)}
  ${crayon(300, 268, -20, '#e0242a', 0.5)}${crayon(14, 40, 30, '#2f74e0', 0.45)}
</svg>
`;
    },
    og: () => {
      const { W, H } = h.OG;
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  ${table(W, H)}
  <g transform="rotate(6 1010 330)">${sheet(S.puddle(), 870, 170, 300)}</g>
  <g transform="rotate(-3 860 320)">${sheet(S.rainbow(), 640, 90, 440)}</g>
  ${crayon(60, 560, -6, '#ffd21f')}${crayon(260, 590, 4, '#23a63a')}
  ${h.title(['Where does rain', 'come from?'], ['#2f74e0', '#e0242a'], '#ffffff', 50, 250).replace(/font-size="92"/, 'font-size="64"')}
</svg>
`;
    }
  };
};
