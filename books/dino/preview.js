// Preview scene for "Dinosaurs" — consumed by tools/build-previews.js (node
// only; not loaded by the book page). A T. rex and a Triceratops face each
// other on a Cretaceous plain, drawn with the book's own builders, with the
// scale child between them.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

module.exports = (h) => {
  // the book's builders are browser scripts that hang off `window`
  global.window = global;
  ['assets/js/kit.js', 'assets/js/dino.js', 'assets/js/animals.js'].forEach(rel =>
    vm.runInThisContext(fs.readFileSync(path.join(h.BOOKS, 'dino', rel), 'utf8')));
  const G = 292;

  // embed a builder's SVG so its ground line (y = 292) lands on screen y = gy
  // (a mirrored picture is placed as an <image>, so the skin filter's
  // lighting is computed before the flip; flipping filtered SVG directly
  // turns it black)
  function stand(svg, x, gy, w, flip) {
    const vb = (svg.match(/viewBox="([^"]+)"/) || [])[1].split(/\s+/).map(Number);
    const k = w / vb[2], y = gy - (G - vb[1]) * k, hh = vb[3] * k;
    if (!flip) return h.embed(svg, x, y, w, false);
    const clean = svg.replace(/<style>[\s\S]*?<\/style>/g, '').replace(/\sdata-part="[^"]*"/g, '');
    const uri = 'data:image/svg+xml;base64,' + Buffer.from(clean).toString('base64');
    return `<image href="${uri}" x="${x}" y="${y.toFixed(1)}" width="${w}" height="${hh.toFixed(1)}" transform="translate(${2 * x + w} 0) scale(-1 1)"/>`;
  }

  function araucaria(x, base, hh, col) {
    let c = '';
    for (let t = 0; t < 4; t++) {
      const y = base - hh * (0.72 + t * 0.085), span = hh * (0.32 - t * 0.06);
      c += `<ellipse cx="${x}" cy="${y.toFixed(1)}" rx="${span.toFixed(1)}" ry="${(hh * 0.03).toFixed(1)}"/>`;
    }
    return `<g fill="${col}"><rect x="${(x - hh * 0.012).toFixed(1)}" y="${base - hh}" width="${(hh * 0.024).toFixed(1)}" height="${hh}"/>${c}</g>`;
  }

  function scene(W, H, extra, opt) {
    const gy = H * opt.ground;
    const rex = window.buildTRex({ child: false, scenery: false });
    const tri = window.buildTriceratops({ child: false, scenery: false });
    const kid = window.DinoKit.child(W * opt.kidX, opt.kidH, gy);
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for "Dinosaurs" — generated by tools/build-previews.js from
       books/dino/preview.js using the book's own builders. Original vector. -->
  <defs>
    <linearGradient id="pvSky" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#8fb6c6"/><stop offset="0.6" stop-color="#d4dccf"/><stop offset="1" stop-color="#f1dfb6"/></linearGradient>
    <radialGradient id="pvSun" cx="0.8" cy="0.2" r="0.5">
      <stop offset="0" stop-color="#fff6da" stop-opacity="0.9"/><stop offset="1" stop-color="#fff6da" stop-opacity="0"/></radialGradient>
    <linearGradient id="pvGround" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#c9b588"/><stop offset="1" stop-color="#ad9465"/></linearGradient>
    <filter id="pvSoft"><feGaussianBlur stdDeviation="${(W / 120).toFixed(1)}"/></filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#pvSky)"/>
  <rect width="${W}" height="${H}" fill="url(#pvSun)"/>
  <g fill="#fff" opacity="0.5" filter="url(#pvSoft)">
    <ellipse cx="${W * 0.2}" cy="${H * 0.14}" rx="${W * 0.12}" ry="${H * 0.04}"/>
    <ellipse cx="${W * 0.62}" cy="${H * 0.1}" rx="${W * 0.16}" ry="${H * 0.045}"/></g>
  <path d="M0 ${H * 0.6} L${W * 0.1} ${H * 0.5} L${W * 0.22} ${H * 0.56} L${W * 0.36} ${H * 0.46} L${W * 0.5} ${H * 0.55} L${W * 0.64} ${H * 0.47} L${W * 0.8} ${H * 0.56} L${W * 0.92} ${H * 0.5} L${W} ${H * 0.55} L${W} ${H} L0 ${H} Z" fill="#a3ada6" opacity="0.75"/>
  <path d="M0 ${H * 0.66} C ${W * 0.3} ${H * 0.6} ${W * 0.6} ${H * 0.64} ${W} ${H * 0.62} L${W} ${H} L0 ${H} Z" fill="#aaa77d"/>
  ${araucaria(W * 0.08, H * 0.68, H * 0.32, '#7f8768')}${araucaria(W * 0.9, H * 0.67, H * 0.36, '#7a8264')}${araucaria(W * 0.56, H * 0.66, H * 0.22, '#8a917a')}
  <path d="M0 ${H * 0.72} C ${W * 0.35} ${H * 0.68} ${W * 0.7} ${H * 0.74} ${W} ${H * 0.7} L${W} ${H} L0 ${H} Z" fill="url(#pvGround)"/>
  ${stand(rex, W * opt.rexX, gy, W * opt.rexW, true)}
  ${stand(tri, W * opt.triX, gy, W * opt.triW, false)}
  ${kid}
  ${extra || ''}
</svg>
`;
  }

  return {
    cover: () => scene(h.COVER.W, h.COVER.H, '',
      { ground: 0.9, rexX: -0.12, rexW: 0.78, triX: 0.44, triW: 0.66, kidX: 0.52, kidH: 22 }),
    og: () => scene(h.OG.W, h.OG.H,
      h.title(['Dino-', 'saurs'], ['#ffe08a', '#ffd54a'], '#5a3a1a', 470, 150),
      { ground: 0.92, rexX: -0.06, rexW: 0.5, triX: 0.6, triW: 0.42, kidX: 0.5, kidH: 40 })
  };
};
