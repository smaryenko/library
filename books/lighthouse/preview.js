// Preview scene for "How a Lighthouse Works": consumed by
// tools/build-previews.js (node only; not loaded by the book page). The
// cover and og image use the book's own pencil pictures (page 1 at dusk,
// page 4's night coast on the og).
const fs = require('fs');
const path = require('path');
const vm = require('vm');
module.exports = (h) => {
  global.window = global;
  ['../../assets/js/drawkit.js', 'assets/js/pencil.js', 'assets/js/scenes.js'].forEach(rel =>
    vm.runInThisContext(fs.readFileSync(path.join(h.BOOKS, 'lighthouse', rel), 'utf8')));
  const S = window.LIGHTHOUSE_SCENES;
  const desk = (W, H) => `<defs>
    <linearGradient id="pvDesk" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#4a3a30"/><stop offset="1" stop-color="#2a201a"/></linearGradient>
    <radialGradient id="pvLamp" cx="0.5" cy="0.4" r="0.6"><stop offset="0" stop-color="#ffe0b0" stop-opacity=".3"/><stop offset="1" stop-color="#ffe0b0" stop-opacity="0"/></radialGradient>
    <filter id="pvSh"><feGaussianBlur stdDeviation="${(W / 90).toFixed(1)}"/></filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#pvDesk)"/><rect width="${W}" height="${H}" fill="url(#pvLamp)"/>`;
  // a sheet of drawing paper with the picture on it
  const sheet = (svg, x, y, w) => `<rect x="${x + w * 0.03}" y="${y + w * 0.04}" width="${w}" height="${w}" fill="#000" opacity="0.45" filter="url(#pvSh)"/>
  <rect x="${x}" y="${y}" width="${w}" height="${w}" fill="#f6efe0"/>${h.embed(svg, x, y, w)}`;
  return {
    cover: () => {
      const { W, H } = h.COVER;
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Preview art for "How a Lighthouse Works": generated by tools/build-previews.js
       from books/lighthouse/preview.js using the book's own builders. Original. -->
  ${desk(W, H)}
  ${sheet(S.dusk(), 62, 12, 276)}
</svg>
`;
    },
    og: () => {
      const { W, H } = h.OG;
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  ${desk(W, H)}
  <g transform="rotate(5 1000 330)">${sheet(S.codes(), 860, 160, 300)}</g>
  <g transform="rotate(-3 860 320)">${sheet(S.dusk(), 640, 90, 440)}</g>
  ${h.title(['How a', 'Lighthouse Works'], ['#ffd87a', '#ffffff'], '#2a201a', 60, 250).replace(/font-size="92"/, 'font-size="64"')}
</svg>
`;
    }
  };
};
